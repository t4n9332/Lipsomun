/**
 * 상품 카테고리 분류 규칙 (공유 모듈)
 * ==================================
 * toss-playwright.mjs(신규 등록 시)와 recategorize-etc.mjs('기타' 정리)가
 * 같은 규칙을 쓰도록 분리했다. 한쪽만 고쳐서 규칙이 갈라지는 일을 막는다.
 *
 * ⚠️ 한글 뒤에 `\b`(단어 경계)를 쓰면 안 된다.
 *    JS 정규식의 `\b`는 [A-Za-z0-9_] 기준이라 한글은 word character가 아니다.
 *    그래서 `쌀\b`는 "담양쌀, 특등급"에서도, "쌀 10kg"에서도 매치되지 않는다
 *    (뒤에 ASCII 문자가 와야만 경계가 생긴다). 실제로 이 규칙들이 전부 죽어
 *    '담양쌀'·'백미밥'·'미역국' 같은 식품이 '기타'로 떨어지고 있었다.
 *    → "뒤에 한글이 오지 않을 것"은 `(?![가-힣])`로 쓴다.
 *      `쌀(?![가-힣])`  : '담양쌀,' O · '쌀 10kg' O · '쌀과자' X
 *      `물(?![가-힣])`  : '생수 2L' 계열 O · '물티슈' X
 */

